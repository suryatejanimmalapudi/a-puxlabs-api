CREATE TABLE diagnostic_file_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_test_request_id BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(150) NOT NULL,
    file_size BIGINT,
    file_type VARCHAR(30) NOT NULL DEFAULT 'SOURCE',
    uploaded_by VARCHAR(100) NOT NULL DEFAULT 'system',
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_diagnostic_attachment_request FOREIGN KEY (lab_test_request_id)
        REFERENCES lab_test_requests(id) ON DELETE CASCADE
);
CREATE INDEX idx_diagnostic_attachment_request ON diagnostic_file_attachment(lab_test_request_id);
