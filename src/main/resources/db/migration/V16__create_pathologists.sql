    ADD CONSTRAINT fk_lab_test_requests_pathologist
        FOREIGN KEY (pathologist_id) REFERENCES pathologist(id);

CREATE INDEX idx_lab_test_requests_pathologist ON lab_test_requests(pathologist_id);

