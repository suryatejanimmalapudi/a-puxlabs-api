CREATE TABLE test_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    package_price NUMERIC(12,2) NOT NULL CHECK (package_price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE test_package_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES test_package(id) ON DELETE CASCADE,
    test_master_id INTEGER NOT NULL REFERENCES tests_master(id),
    package_test_price NUMERIC(12,2) NOT NULL CHECK (package_test_price >= 0),
    CONSTRAINT uk_test_package_item UNIQUE (package_id, test_master_id)
);

CREATE INDEX idx_test_package_item_package ON test_package_item(package_id);
CREATE INDEX idx_test_package_item_test ON test_package_item(test_master_id);

CREATE TABLE lab_order_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES lab_orders(id) ON DELETE CASCADE,
    package_id BIGINT NOT NULL REFERENCES test_package(id),
    package_code VARCHAR(50) NOT NULL,
    package_name VARCHAR(255) NOT NULL,
    package_price NUMERIC(12,2) NOT NULL CHECK (package_price >= 0)
);

CREATE INDEX idx_lab_order_packages_order ON lab_order_packages(order_id);
